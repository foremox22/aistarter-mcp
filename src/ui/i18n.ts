const dictionaries: Record<Locale, Dict> = { en, th, zh, ja, id, vi, ru };

export function t(locale: Locale, key: string): string {
  return dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
}

export function questionText(locale: Locale, questionId: string): string {
  return t(locale, `q_${questionId}`);
}

export function detectLocale(acceptLanguage: string | undefined): Locale {
  if (!acceptLanguage) return "en";
  const candidates = acceptLanguage
    .split(",")
    .map((part) => part.trim().split(";")[0]?.toLowerCase().split("-")[0]);
  for (const c of candidates) {
    if ((LOCALES as readonly string[]).includes(c ?? "")) return c as Locale;
  }
  return "en";
}

export function isLocale(value: string | null | undefined): value is Locale {
  return !!value && (LOCALES as readonly string[]).includes(value);
}
